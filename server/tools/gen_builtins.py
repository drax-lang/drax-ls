#!/usr/bin/env python3
"""Generate src/builtins.js from the Drax C sources (src/dbuiltin.c)."""
import re, sys, json, os

src = sys.argv[1] if len(sys.argv) > 1 else '../../drax/src/dbuiltin.c'
text = open(src).read()

globals_ = {}
for m in re.finditer(r'reg\(vm,\s*"(\w+)",\s*(\d+),', text):
    globals_[m.group(1)] = int(m.group(2))

modules = {}
cur = None
for line in text.splitlines():
    m = re.search(r'new_native_module\(vm,\s*"(\w+)"', line)
    if m:
        cur = m.group(1)
        modules.setdefault(cur, {})
        continue
    m = re.match(r'\s*\{(\d+),\s*"(\w+)",', line)
    if m and cur:
        modules[cur].setdefault(m.group(2), [])
        modules[cur][m.group(2)].append(int(m.group(1)))

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'builtins.js')
with open(out, 'w') as f:
    f.write('// Generated by tools/gen_builtins.py from drax/src/dbuiltin.c. Do not edit.\n')
    f.write('"use strict";\n\n')
    f.write('const GLOBALS = %s;\n\n' % json.dumps(globals_, indent=2))
    f.write('const MODULES = %s;\n\n' % json.dumps(modules, indent=2))
    f.write('module.exports = { GLOBALS, MODULES };\n')
print({k: len(v) for k, v in modules.items()}, len(globals_))
